#!/usr/bin/env python3
"""
Exports every table in the Supabase Postgres database (except the auth and
storage schemas, and Supabase's own internal schemas) and converts it into a
single MySQL 8 .sql file that recreates the tables, indexes, foreign keys,
CHECK constraints, views and data.

Two phases, so the slow network part only has to happen once:

  1. download -- reads the Postgres DDL for every table/index/constraint/view
     (as Postgres itself prints it) into <out-dir>/download/schema.json, and
     streams every row to <out-dir>/download/<schema>.<table>.jsonl
  2. convert  -- parses that DDL with sqlglot, rewrites the syntax tree for
     MySQL, and writes <out-dir>/mysql_dump.sql (data INSERTs are also
     generated by sqlglot, so quoting/escaping is MySQL's)

Usage:
  conda activate general
  pip install sqlglot "psycopg[binary]"
  DATABASE_URL='postgresql://postgres.<ref>:<password>@<pooler-host>:5432/postgres' \
    python scripts/pg-to-mysql.py
  python scripts/pg-to-mysql.py --skip-download   # re-convert from local files

  mysql -u <user> -p <database> < pg_export/mysql_dump.sql

Use the database password from Supabase -> Project Settings -> Database (the
API keys won't work here); the session-mode pooler URL works over IPv4.

Conversion notes:
  - Tables in `public` keep their names; tables in any other schema become
    `<schema>__<table>`, since a MySQL database has no schemas.
  - uuid -> CHAR(36), timestamptz -> DATETIME(6) in UTC, jsonb/arrays -> JSON,
    boolean -> TINYINT(1), serial/identity -> AUTO_INCREMENT.
  - text -> LONGTEXT, except text columns used in a key/index, which become
    VARCHAR(n) sized to fit InnoDB's 3072-byte index limit (the script fails
    if existing data is longer than that).
  - Collation is utf8mb4_0900_bin so uniqueness and comparisons stay
    case-sensitive, as they are in Postgres.
  - CHECK constraints and views are translated by sqlglot and written at the
    end of the file (after all data), so if MySQL rejects one, every table and
    row is already loaded. Views sqlglot can't translate are hand-written in
    VIEW_OVERRIDES.
  - SCHEMA_ONLY_TABLES (deleted_rows) are created empty; EXCLUDED_TABLES
    (ans_data_upload) and EXCLUDED_COLUMNS (ans_data.upload_id) are left out.
  - Not converted (reported as warnings): triggers, functions, RLS policies,
    expression/non-btree indexes, partial indexes other than
    `WHERE col IS NOT NULL`, column defaults that aren't a
    literal, now(), or a uuid generator, and any CHECK/view that sqlglot
    can't express in MySQL.
"""

